logger = logging.getLogger(__name__)

_OUTBOX_STATUSES = ("pending", "processing", "retry", "complete", "dead")


@dataclass
class Memory:
    """A single memory entry."""

    id: str
    content: str
    summary: str
    category: str
    tier: str
    key_topics: list[str]
    source: str
    embedding: Optional[bytes]  # serialized numpy array
    created_at: float
    accessed_at: float
    expires_at: Optional[float]  # None = never expires (persist tier)


@dataclass(frozen=True)
class OutboxJob:
    """One leased durable capture-processing job."""

    id: str
    raw_capture_id: str
    event_type: str
    attempts: int
    content: str
    source: str
    project: str
    agent: str
    user_id: Optional[str]
    workspace_id: Optional[str]
    project_id: Optional[str]
    repository_id: Optional[str]
    task_id: Optional[str]
    session_id: Optional[str]
    requested_category: Optional[str]
    requested_tier: Optional[str]
    gate_decision: Optional[str]
    gate_confidence: Optional[float]
    gate_backend: Optional[str]
    gate_fallback_used: Optional[bool]


class MemoryStore:
    """
    SQLite-backed memory store with TTL-based expiry.

    SCHEMA DESIGN:
    - id: UUID for unique identification across instances
    - content: raw text (what was said)
    - summary: extracted summary (what it means)
    - embedding: binary vector for semantic search (384 floats = 1536 bytes)
    - tier: cold/active/persist → controls TTL
    - expires_at: unix timestamp for auto-expiry (NULL = never)
    - accessed_at: for LRU-style promotion during consolidation
    """

    def __init__(
        self,
        db_path: Path,
        cold_ttl: int = 86400,
        active_ttl: int = 2592000,
        persist_ttl: int = -1,
    ):
        self.db_path = db_path
        self.ttl_config = {
            "cold": cold_ttl,  # 1 day
            "active": active_ttl,  # 30 days
            "persist": persist_ttl,  # -1 = forever
        }
        self._init_db()

    @contextmanager
    def _connect(self):
        """Open a transactional connection with enforcement enabled."""
        connection = sqlite3.connect(str(self.db_path))
        connection.execute("PRAGMA foreign_keys=ON")
        connection.execute("PRAGMA busy_timeout=5000")
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    def _init_db(self):
        """Bring the database to the latest supported canonical schema."""
        run_migrations(self.db_path)
        logger.info("Memory store initialized at %s", self.db_path)

    def enqueue_capture(
        self,
        content: str,
        *,
        source: str = "",
        project: str = "",
        agent: str = "",
        user_id: Optional[str] = None,
        workspace_id: Optional[str] = None,
        project_id: Optional[str] = None,
        repository_id: Optional[str] = None,
        task_id: Optional[str] = None,
        session_id: Optional[str] = None,
        category: Optional[str] = None,
        tier: Optional[str] = None,
    ) -> tuple[str, str]:
        """Atomically persist a raw capture and its processing job."""
        now = time.time()
        capture_id = f"mem_{int(now)}_{uuid.uuid4().hex[:6]}"
        job_id = f"outbox_{uuid.uuid4().hex}"
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            conn.execute(
                """
                INSERT INTO raw_captures (
                    id, content, source, project, agent,
                    user_id, workspace_id, project_id, repository_id,
                    task_id, session_id,
                    requested_category, requested_tier,
                    received_at, updated_at
                )
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    capture_id,
                    content,
                    source,
                    project,
                    agent,
                    user_id,
                    workspace_id,
                    project_id,
                    repository_id,
                    task_id,
                    session_id,
                    category,
                    tier,
                    now,
                    now,
                ),
            )
            conn.execute(
                """
                INSERT INTO outbox_jobs (
                    id, raw_capture_id, event_type, status, attempts,
                    available_at, created_at, updated_at
                )
                VALUES (?, ?, 'capture.process', 'pending', 0, ?, ?, ?)
                """,
                (job_id, capture_id, now, now, now),
            )
        return capture_id, job_id

    def persist_raw_capture(
        self,
        content: str,
        *,
        source: str = "",
        project: str = "",
        agent: str = "",
    ) -> str:
        """Compatibility wrapper that now creates a durable outbox job."""
        capture_id, _job_id = self.enqueue_capture(
            content, source=source, project=project, agent=agent
        )
        return capture_id

    def claim_outbox_job(
        self,
        *,
        lease_seconds: float,
        job_id: str | None = None,
        now: float | None = None,
    ) -> OutboxJob | None:
        """Atomically claim one due or expired capture-processing job."""
        claimed_at = time.time() if now is None else now
        due = """
            ((j.status IN ('pending', 'retry') AND j.available_at <= ?)
             OR (j.status = 'processing' AND j.lease_expires_at <= ?))
        """
        params: list[object] = [claimed_at, claimed_at]
        if job_id is not None:
            due += " AND j.id = ?"
            params.append(job_id)
        with self._connect() as conn:
            conn.row_factory = sqlite3.Row
            conn.execute("BEGIN IMMEDIATE")
            row = conn.execute(
                f"""
                SELECT j.id
                FROM outbox_jobs j
                WHERE {due}
                ORDER BY j.available_at, j.created_at
                LIMIT 1
                """,
                params,
            ).fetchone()
            if row is None:
                return None
            selected_id = str(row["id"])
            conn.execute(
                """
                UPDATE outbox_jobs
                SET status = 'processing', attempts = attempts + 1,
                    lease_expires_at = ?, updated_at = ?
                WHERE id = ?
                """,
                (claimed_at + lease_seconds, claimed_at, selected_id),
            )
            conn.execute(
                """
                UPDATE raw_captures
                SET status = 'processing', updated_at = ?
                WHERE id = (
                    SELECT raw_capture_id FROM outbox_jobs WHERE id = ?
                )
                """,
                (claimed_at, selected_id),
            )
            claimed = conn.execute(
                """
                SELECT
                    j.id, j.raw_capture_id, j.event_type, j.attempts,
                    r.content, r.source, r.project, r.agent,
                    r.user_id, r.workspace_id, r.project_id, r.repository_id,
                    r.task_id, r.session_id,
                    r.requested_category, r.requested_tier,
                    r.gate_decision, r.gate_confidence, r.gate_backend,
                    r.gate_fallback_used
                FROM outbox_jobs j
                JOIN raw_captures r ON r.id = j.raw_capture_id
                WHERE j.id = ?
                """,
                (selected_id,),
            ).fetchone()
        fallback = claimed["gate_fallback_used"]
        return OutboxJob(
            id=str(claimed["id"]),
            raw_capture_id=str(claimed["raw_capture_id"]),
            event_type=str(claimed["event_type"]),
            attempts=int(claimed["attempts"]),
            content=str(claimed["content"]),
            source=str(claimed["source"]),
            project=str(claimed["project"]),
            agent=str(claimed["agent"]),
            user_id=claimed["user_id"],
            workspace_id=claimed["workspace_id"],
            project_id=claimed["project_id"],
            repository_id=claimed["repository_id"],
            task_id=claimed["task_id"],
            session_id=claimed["session_id"],
            requested_category=claimed["requested_category"],
            requested_tier=claimed["requested_tier"],
            gate_decision=claimed["gate_decision"],
            gate_confidence=claimed["gate_confidence"],
            gate_backend=claimed["gate_backend"],
            gate_fallback_used=None if fallback is None else bool(fallback),
        )

    def ensure_capture_memory(
        self,
        job: OutboxJob,
        *,
        gate_decision: str,
        gate_confidence: float,
        gate_backend: str,
        gate_fallback_used: bool,
        category: str,
        tier: str,
    ) -> str:
        """Persist the accepted gate result and provisional memory idempotently."""
        now = time.time()
        ttl = self.ttl_config.get(tier, self.ttl_config["active"])
        expires_at = None if ttl == -1 else now + ttl
        lifecycle_state = {
            "cold": "ephemeral",
            "active": "active",
            "persist": "stable",
        }.get(tier, "active")
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            existing = conn.execute(
                """
                SELECT content, source, project, agent,
                       user_id, workspace_id, project_id, repository_id,
                       task_id, session_id
                FROM memories WHERE id = ?
                """,
                (job.raw_capture_id,),
            ).fetchone()
            expected = (
                job.content,
                job.source,
                job.project,
                job.agent,
                job.user_id,
                job.workspace_id,
                job.project_id,
                job.repository_id,
                job.task_id,
                job.session_id,
            )
            if existing is None:
                conn.execute(
                    """
                    INSERT INTO memories (
                        id, content, summary, category, tier, key_topics,
                        source, embedding, created_at, accessed_at, expires_at,
                        project, agent, processing_status,
                        user_id, workspace_id, project_id, repository_id,
                        task_id, session_id, lifecycle_state
                    )
                    VALUES (
                        ?, ?, ?, ?, ?, '[]', ?, NULL, ?, ?, ?, ?, ?, 'pending',
                        ?, ?, ?, ?, ?, ?, ?
                    )
                    """,
                    (
                        job.raw_capture_id,
                        job.content,
                        job.content[:200],
                        category,
                        tier,
                        job.source,
                        now,
                        now,
                        expires_at,
                        job.project,
                        job.agent,
                        job.user_id,
                        job.workspace_id,
                        job.project_id,
                        job.repository_id,
                        job.task_id,
                        job.session_id,
                        lifecycle_state,
                    ),
                )
            elif tuple(existing) != expected:
                raise ValueError(f"canonical capture mismatch for {job.raw_capture_id}")
            conn.execute(
                """
                UPDATE raw_captures
                SET gate_decision = ?, gate_confidence = ?, gate_backend = ?,
                    gate_fallback_used = ?, memory_id = ?, status = 'processing',
                    error = '', updated_at = ?
                WHERE id = ?
                """,
                (
                    gate_decision,
                    gate_confidence,
                    gate_backend,
                    int(gate_fallback_used),
                    job.raw_capture_id,
                    now,
                    job.raw_capture_id,
                ),
            )
        return job.raw_capture_id

    def record_gate_result(
        self,
        job: OutboxJob,
        *,
        gate_decision: str,
        gate_confidence: float,
        gate_backend: str,
        gate_fallback_used: bool,
    ) -> tuple[str, float, str, bool]:
        """Persist and return the canonical first gate result for a capture."""
        now = time.time()
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            cursor = conn.execute(
                """
                UPDATE raw_captures
                SET gate_decision = ?, gate_confidence = ?, gate_backend = ?,
                    gate_fallback_used = ?, error = '', updated_at = ?
                WHERE id = ? AND gate_decision IS NULL
                """,
                (
                    gate_decision,
                    gate_confidence,
                    gate_backend,
                    int(gate_fallback_used),
                    now,
                    job.raw_capture_id,
                ),
            )
            if cursor.rowcount not in (0, 1):
                raise RuntimeError(
                    f"unexpected gate-result update count for {job.raw_capture_id}"
                )
            canonical = conn.execute(
                """
                SELECT gate_decision, gate_confidence, gate_backend,
                       gate_fallback_used
                FROM raw_captures WHERE id = ?
                """,
                (job.raw_capture_id,),
            ).fetchone()
            if canonical is None or canonical[0] is None:
                raise RuntimeError(
                    f"gate result was not persisted for {job.raw_capture_id}"
                )
        return (
            str(canonical[0]),
            float(canonical[1]),
            str(canonical[2]),
            bool(canonical[3]),
        )

    def complete_skipped_outbox_job(
        self,
        job: OutboxJob,
        *,
        gate_decision: str,
        gate_confidence: float,
        gate_backend: str,
        gate_fallback_used: bool,
    ) -> None:
        """Atomically persist a skip result and complete its outbox job."""
        now = time.time()
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            conn.execute(
                """
                UPDATE raw_captures
                SET gate_decision = ?, gate_confidence = ?, gate_backend = ?,
                    gate_fallback_used = ?, status = 'skipped', memory_id = NULL,
                    error = '', updated_at = ?
                WHERE id = ?
                """,
                (
                    gate_decision,
                    gate_confidence,
                    gate_backend,
                    int(gate_fallback_used),
                    now,
                    job.raw_capture_id,
                ),
            )
            self._mark_outbox_complete(conn, job.id, now)

    @staticmethod
    def _mark_outbox_complete(
        conn: sqlite3.Connection, job_id: str, now: float
    ) -> None:
        cursor = conn.execute(
            """
            UPDATE outbox_jobs
            SET status = 'complete', lease_expires_at = NULL,
                last_error = '', updated_at = ?, completed_at = ?
            WHERE id = ? AND status = 'processing'
            """,
            (now, now, job_id),
        )
        if cursor.rowcount != 1:
            raise RuntimeError(f"outbox lease lost before completion: {job_id}")

    def complete_outbox_job(
        self, job: OutboxJob, memory_id: str, *, status: str = "complete"
    ) -> None:
        """Atomically complete the durable job and its raw capture."""
        now = time.time()
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            conn.execute(
                """
                UPDATE raw_captures
                SET status = ?, memory_id = ?, error = '', updated_at = ?
                WHERE id = ?
                """,
                (status, memory_id, now, job.raw_capture_id),
            )
            self._mark_outbox_complete(conn, job.id, now)

    def fail_outbox_job(
        self,
        job: OutboxJob,
        error: str,
        *,
        max_attempts: int,
        retry_base_seconds: float,
        now: float | None = None,
    ) -> tuple[str, float]:
        """Schedule retry or atomically mark exhausted work dead."""
        failed_at = time.time() if now is None else now
        message = error[:1000]
        terminal = job.attempts >= max_attempts
        delay = (
            0.0
            if terminal
            else min(300.0, retry_base_seconds * (2 ** max(0, job.attempts - 1)))
        )
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            if terminal:
                cursor = conn.execute(
                    """
                    UPDATE outbox_jobs
                    SET status = 'dead', lease_expires_at = NULL,
                        last_error = ?, updated_at = ?, completed_at = ?
                    WHERE id = ? AND status = 'processing'
                    """,
                    (message, failed_at, failed_at, job.id),
                )
                raw_status = "failed"
                memory_status = "failed"
            else:
                cursor = conn.execute(
                    """
                    UPDATE outbox_jobs
                    SET status = 'retry', available_at = ?,
                        lease_expires_at = NULL, last_error = ?,
                        updated_at = ?, completed_at = NULL
                    WHERE id = ? AND status = 'processing'
                    """,
                    (failed_at + delay, message, failed_at, job.id),
                )
                raw_status = "pending"
                memory_status = "pending"
            if cursor.rowcount != 1:
                raise RuntimeError(f"outbox lease lost after failure: {job.id}")
            conn.execute(
                """
                UPDATE raw_captures
                SET status = ?, error = ?, updated_at = ?
                WHERE id = ?
                """,
                (raw_status, message, failed_at, job.raw_capture_id),
            )
            conn.execute(
                """
                UPDATE memories
                SET processing_status = ?, processing_error = ?
                WHERE id = ?
                """,
                (memory_status, message, job.raw_capture_id),
            )
        return ("dead" if terminal else "retry", delay)

    def retry_dead_outbox_job(self, job_id: str) -> bool:
        """Reset one dead job for an operator-requested retry."""
        now = time.time()
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            row = conn.execute(
                "SELECT raw_capture_id FROM outbox_jobs WHERE id = ? AND status = 'dead'",
                (job_id,),
            ).fetchone()
            if row is None:
                return False
            raw_capture_id = str(row[0])
            conn.execute(
                """
                UPDATE outbox_jobs
                SET status = 'pending', attempts = 0, available_at = ?,
                    lease_expires_at = NULL, last_error = '',
                    updated_at = ?, completed_at = NULL
                WHERE id = ?
                """,
                (now, now, job_id),
            )
            conn.execute(
                """
                UPDATE raw_captures
                SET status = 'pending', error = '', updated_at = ?
                WHERE id = ?
                """,
                (now, raw_capture_id),
            )
            conn.execute(
                """
                UPDATE memories
                SET processing_status = 'pending', processing_error = ''
                WHERE id = ?
                """,
                (raw_capture_id,),
            )
        return True

    def outbox_job(self, job_id: str) -> dict | None:
        """Return non-content job metadata for diagnostics."""
        with self._connect() as conn:
            conn.row_factory = sqlite3.Row
            row = conn.execute(
                """
                SELECT id, raw_capture_id, event_type, status, attempts,
                       available_at, lease_expires_at, last_error,
                       created_at, updated_at, completed_at
                FROM outbox_jobs WHERE id = ?
                """,
                (job_id,),
            ).fetchone()
        return dict(row) if row else None

    def complete_raw_capture(
        self, capture_id: str, memory_id: str | None, *, status: str = "complete"
    ) -> None:
        """Compatibility helper for callers managing raw state directly."""
        with self._connect() as conn:
            conn.execute(
                """
                UPDATE raw_captures
                SET status = ?, memory_id = ?, error = '', updated_at = ?
                WHERE id = ?
                """,
                (status, memory_id, time.time(), capture_id),
            )

    def fail_raw_capture(self, capture_id: str, error: str) -> None:
        """Compatibility helper for callers managing raw state directly."""
        with self._connect() as conn:
            conn.execute(
                """
                UPDATE raw_captures
                SET status = 'failed', error = ?, updated_at = ?
                WHERE id = ?
                """,
                (error[:1000], time.time(), capture_id),
            )

    def reserve_event(self, event_id: str, stale_after: float = 300.0) -> bool:
        """Atomically reserve an external event for idempotent ingestion."""
        now = time.time()
        with self._connect() as conn:
            conn.execute("PRAGMA foreign_keys=ON")
            row = conn.execute(
                "SELECT status, updated_at FROM ingest_events WHERE event_id = ?",
                (event_id,),
            ).fetchone()
            if row is None:
                conn.execute(
                    """
                    INSERT INTO ingest_events
                        (event_id, status, created_at, updated_at)
                    VALUES (?, 'processing', ?, ?)
                    """,
                    (event_id, now, now),
                )
                return True
            if row[0] == "failed" or (
                row[0] == "processing" and row[1] < now - stale_after
            ):
                conn.execute(
                    """
                    UPDATE ingest_events
                    SET status = 'processing', attempts = attempts + 1,
                        last_error = '', updated_at = ?
                    WHERE event_id = ?
                    """,
                    (now, event_id),
                )
                return True
            return False

    def complete_event(self, event_id: str, capture_id: str | None) -> None:
        """Commit idempotency after either a memory or raw capture is durable."""
        now = time.time()
        with self._connect() as conn:
            conn.execute("PRAGMA foreign_keys=ON")
            memory_id = None
            raw_capture_id = None
            if capture_id:
                if conn.execute(
                    "SELECT 1 FROM memories WHERE id = ?", (capture_id,)
                ).fetchone():
                    memory_id = capture_id
                elif conn.execute(
                    "SELECT 1 FROM raw_captures WHERE id = ?", (capture_id,)
                ).fetchone():
                    raw_capture_id = capture_id
            conn.execute(
                """
                UPDATE ingest_events
                SET status = 'complete', memory_id = ?, raw_capture_id = ?,
                    updated_at = ?, processed_at = ?
                WHERE event_id = ?
                """,
                (memory_id, raw_capture_id, now, now, event_id),
            )

    def fail_event(self, event_id: str, error: str) -> None:
        """Release a failed event so JetStream redelivery can retry it."""
        with self._connect() as conn:
            conn.execute(
                """
                UPDATE ingest_events
                SET status = 'failed', last_error = ?, updated_at = ?
                WHERE event_id = ?
                """,
                (error[:1000], time.time(), event_id),
            )

    def store(
        self,
        content: str,
        summary: str,
        category: str,
        tier: str,
        key_topics: list[str],
        source: str = "",
        embedding: Optional[bytes] = None,
        project: str = "",
        agent: str = "",
        user_id: Optional[str] = None,
        workspace_id: Optional[str] = None,
        project_id: Optional[str] = None,
        repository_id: Optional[str] = None,
        task_id: Optional[str] = None,
        session_id: Optional[str] = None,
        processing_status: str = "complete",
        memory_id: str | None = None,
    ) -> str:
        """
        Save a memory and return its ID.

        PATTERN: Auto-generated IDs
        We use UUIDs instead of auto-incrementing integers because:
        - No coordination needed between instances (safe for distributed systems)
        - Can generate ID before inserting (useful for embedding generation)
        - Can't guess other memory IDs from one ID (security)
        """
        now = time.time()
        mem_id = memory_id or f"mem_{int(now)}_{uuid.uuid4().hex[:6]}"

        # Calculate expiry based on tier
        ttl = self.ttl_config.get(tier, self.ttl_config["active"])
        expires_at = None if ttl == -1 else now + ttl
        lifecycle_state = {
            "cold": "ephemeral",
            "active": "active",
            "persist": "stable",
        }.get(tier, "active")

        with self._connect() as conn:
            conn.execute(
                """
                INSERT INTO memories (id, content, summary, category, tier, key_topics,
                                      source, embedding, created_at, accessed_at, expires_at,
                                      project, agent, processing_status,
                                      user_id, workspace_id, project_id, repository_id,
                                      task_id, session_id, lifecycle_state)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
                (
                    mem_id,
                    content,
                    summary,
                    category,
                    tier,
                    json.dumps(key_topics),
                    source,
                    embedding,
                    now,
                    now,
                    expires_at,
                    project,
                    agent,
                    processing_status,
                    user_id,
                    workspace_id,
                    project_id,
                    repository_id,
                    task_id,
                    session_id,
                    lifecycle_state,
                ),
            )

        logger.info(f"Stored memory {mem_id} (tier={tier}, category={category})")
        return mem_id

    def update_enrichment(
        self,
        mem_id: str,
        *,
        summary: str,
        category: str,
        tier: str,
        key_topics: list[str],
        processing_status: str = "complete",
        processing_error: str = "",
    ) -> None:
        """Apply extracted metadata after the raw memory is durable."""
        now = time.time()
        ttl = self.ttl_config.get(tier, self.ttl_config["active"])
        expires_at = None if ttl == -1 else now + ttl
        retention_review_at = now + self.ttl_config["active"]
        lifecycle_state = {
            "cold": "ephemeral",
            "active": "active",
            "persist": "stable",
        }.get(tier, "active")
        with self._connect() as conn:
            conn.execute(
                """
                UPDATE memories
                SET summary = ?, category = ?, tier = ?, key_topics = ?,
                    expires_at = ?,
                    lifecycle_state = CASE
                        WHEN pinned = 1 THEN lifecycle_state ELSE ? END,
                    retention_review_at = ?,
                    processing_status = ?, processing_error = ?
                WHERE id = ?
                """,
                (
                    summary,
                    category,
                    tier,
                    json.dumps(key_topics),
                    expires_at,
                    lifecycle_state,
                    retention_review_at,
                    processing_status,
                    processing_error[:1000],
                    mem_id,
                ),
            )

