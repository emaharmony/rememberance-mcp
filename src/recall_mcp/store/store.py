    def stale_embeddings(self, model: str, limit: int = 100) -> list[dict]:
        """Return missing, failed, or content-changed embedding candidates."""
        with self._connect() as conn:
            conn.row_factory = sqlite3.Row
            rows = conn.execute(
                """
                SELECT id, content, embedding_model, embedding_content_hash,
                       embedding_status
                FROM memories
                WHERE embedding IS NULL OR embedding_status != 'ready'
                   OR embedding_model != ?
                ORDER BY created_at DESC
                LIMIT ?
                """,
                (model, limit),
            ).fetchall()
            candidates = [dict(row) for row in rows]
            remaining = limit - len(candidates)
            if remaining > 0:
                ready_rows = conn.execute(
                    """
                    SELECT id, content, embedding_model,
                           embedding_content_hash, embedding_status
                    FROM memories
                    WHERE embedding IS NOT NULL
                      AND embedding_status = 'ready'
                      AND embedding_model = ?
                    ORDER BY created_at DESC
                    LIMIT ?
                    """,
                    (model, max(remaining * 4, remaining)),
                ).fetchall()
                for row in ready_rows:
                    memory = dict(row)
                    digest = hashlib.sha256(
                        memory["content"].encode("utf-8")
                    ).hexdigest()
                    if digest != memory["embedding_content_hash"]:
                        candidates.append(memory)
                        if len(candidates) >= limit:
                            break
            return candidates[:limit]

    def search(
        self,
        query: str,
        category: Optional[str] = None,
        tier: Optional[str] = None,
        project: Optional[str] = None,
        agent: Optional[str] = None,
        limit: int = 10,
        include_cold: bool = False,
    ) -> list[dict]:
        """
        Search memories by text match and metadata filters.

        NOTE: This does keyword matching for now. Semantic search (via
        embeddings) is available via search_semantic() which uses
        cosine similarity on vector embeddings.
        """
        with self._connect() as conn:
            conn.row_factory = sqlite3.Row
            sql = "SELECT * FROM memories WHERE 1=1"
            params: list[object] = []

            # FTS-style keyword search across content and summary
            if query:
                sql += " AND (content LIKE ? OR summary LIKE ?)"
                params.extend([f"%{query}%", f"%{query}%"])

            if category:
                sql += " AND category = ?"
                params.append(category)
            if tier:
                sql += " AND tier = ?"
                params.append(tier)

            if project:
                sql += " AND project = ?"
                params.append(project)
            if agent:
                sql += " AND agent = ?"
                params.append(agent)
            # Filter out expired memories
            now = time.time()
            if include_cold:
                sql += """
                    AND ((expires_at IS NULL OR expires_at > ?)
                         OR lifecycle_state = 'cold')
                """
            else:
                sql += """
                    AND lifecycle_state NOT IN ('cold', 'archived')
                    AND (expires_at IS NULL OR expires_at > ?)
                """
            params.append(now)

            sql += " ORDER BY accessed_at DESC LIMIT ?"
            params.append(limit)

            rows = conn.execute(sql, params).fetchall()
            return [dict(r) for r in rows]

    def get(self, mem_id: str) -> Optional[dict]:
        """Get a memory by ID and record an explicit access."""
        with self._connect() as conn:
            conn.row_factory = sqlite3.Row
            row = conn.execute(
                "SELECT * FROM memories WHERE id = ?", (mem_id,)
            ).fetchone()
            if row:
                # Touch: update accessed_at for LRU during consolidation
                conn.execute(
                    "UPDATE memories SET accessed_at = ?, access_count = access_count + 1 WHERE id = ?",
                    (time.time(), mem_id),
                )
                return dict(row)
        return None

    def delete(self, mem_id: str) -> bool:
        """Delete a memory by ID."""
        with self._connect() as conn:
            cursor = conn.execute("DELETE FROM memories WHERE id = ?", (mem_id,))
            return cursor.rowcount > 0

    def consolidate(self) -> dict:
        """Demote expired memories reversibly; never delete automatically."""
        now = time.time()
        results = {
            "expired_deleted": 0,
            "expired_demoted": 0,
            "promoted": 0,
            "demoted": 0,
        }

        with self._connect() as conn:
            expired = conn.execute(
                """
                SELECT id, lifecycle_state FROM memories
                WHERE pinned = 0
                  AND lifecycle_state NOT IN ('cold', 'archived')
                  AND expires_at IS NOT NULL AND expires_at < ?
                ORDER BY id
                """,
                (now,),
            ).fetchall()
            for memory in expired:
                conn.execute(
                    """
                    INSERT INTO memory_lifecycle_audit (
                        id, memory_id, previous_state, new_state, reason,
                        actor_id, policy_version, created_at
                    ) VALUES (?, ?, ?, 'cold', 'retention_review',
                              NULL, 'utility-v1', ?)
                    """,
                    (
                        f"lifecycle_{uuid.uuid4().hex}",
                        memory[0],
                        memory[1],
                        now,
                    ),
                )
            cursor = conn.execute(
                """
                UPDATE memories
                SET lifecycle_state = 'cold', retention_review_at = ?
                WHERE pinned = 0
                  AND lifecycle_state NOT IN ('cold', 'archived')
                  AND expires_at IS NOT NULL AND expires_at < ?
                """,
                (now, now),
            )
            results["expired_demoted"] = cursor.rowcount
            conn.execute("UPDATE memories SET expires_at = NULL WHERE pinned = 1")

        logger.info(f"Consolidation: {results}")
        return results

    def operational_stats(self) -> dict:
        now = time.time()
        with self._connect() as conn:
            embedding = {
                row[0]: row[1]
                for row in conn.execute(
                    "SELECT embedding_status, COUNT(*) FROM memories GROUP BY embedding_status"
                )
            }
            processing = {
                row[0]: row[1]
                for row in conn.execute(
                    "SELECT processing_status, COUNT(*) FROM memories GROUP BY processing_status"
                )
            }
            events = {
                row[0]: row[1]
                for row in conn.execute(
                    "SELECT status, COUNT(*) FROM ingest_events GROUP BY status"
                )
            }
            outbox = dict.fromkeys(_OUTBOX_STATUSES, 0)
            outbox.update(
                {
                    row[0]: row[1]
                    for row in conn.execute(
                        "SELECT status, COUNT(*) FROM outbox_jobs GROUP BY status"
                    )
                }
            )
            oldest_due = conn.execute(
                """
                SELECT MIN(
                    CASE WHEN status = 'processing'
                         THEN lease_expires_at ELSE available_at END
                )
                FROM outbox_jobs
                WHERE (status IN ('pending', 'retry') AND available_at <= ?)
                   OR (status = 'processing' AND lease_expires_at <= ?)
                """,
                (now, now),
            ).fetchone()[0]
            active_leases = conn.execute(
                """
                SELECT COUNT(*) FROM outbox_jobs
                WHERE status = 'processing' AND lease_expires_at > ?
                """,
                (now,),
            ).fetchone()[0]
        return {
            "embeddings": embedding,
            "processing": processing,
            "ingest_events": events,
            "outbox": outbox,
            "outbox_oldest_due_seconds": (
                max(0.0, now - float(oldest_due)) if oldest_due is not None else 0.0
            ),
            "outbox_active_leases": active_leases,
        }

    def integrity_report(self, *, quick: bool = False) -> dict:
        """Check SQLite integrity, foreign keys, and graph orphan relations."""
        with self._connect() as conn:
            pragma = "quick_check" if quick else "integrity_check"
            integrity_rows = [
                str(row[0]) for row in conn.execute(f"PRAGMA {pragma}").fetchall()
            ]
            foreign_key_errors = [
                list(row) for row in conn.execute("PRAGMA foreign_key_check").fetchall()
            ]
            tables = {
                row[0]
                for row in conn.execute(
                    "SELECT name FROM sqlite_master WHERE type = 'table'"
                ).fetchall()
            }
            schema_version = conn.execute(
                "SELECT COALESCE(MAX(version), 0) FROM schema_migrations"
            ).fetchone()[0]
            orphans: dict[str, int] = {}
            if {"memory_entities", "memories", "entities"}.issubset(tables):
                orphans["memory_entities"] = conn.execute(
                    """
                    SELECT COUNT(*) FROM memory_entities me
                    LEFT JOIN memories m ON m.id = me.memory_id
                    LEFT JOIN entities e ON e.id = me.entity_id
                    WHERE m.id IS NULL OR e.id IS NULL
                    """
                ).fetchone()[0]
            if {"edges", "entities"}.issubset(tables):
                orphans["edges"] = conn.execute(
                    """
                    SELECT COUNT(*) FROM edges g
                    LEFT JOIN entities s ON s.id = g.source_id
                    LEFT JOIN entities t ON t.id = g.target_id
                    WHERE s.id IS NULL OR t.id IS NULL
                    """
                ).fetchone()[0]

        return {
            "integrity": integrity_rows,
            "foreign_key_errors": foreign_key_errors,
            "orphans": orphans,
            "schema_version": schema_version,
            "schema_current": schema_version == CURRENT_SCHEMA_VERSION,
            "ok": schema_version == CURRENT_SCHEMA_VERSION
            and integrity_rows == ["ok"]
            and not foreign_key_errors
            and not any(orphans.values()),
        }

    def count(self) -> int:
        """Return total number of memories (including expired)."""
        with self._connect() as conn:
            return conn.execute("SELECT COUNT(*) FROM memories").fetchone()[0]
